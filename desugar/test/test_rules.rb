  def test_every_rule_has_an_example
    assert_equal [], Desugar::RULES.map(&:to_s) - EXAMPLES.keys
    assert_equal [], EXAMPLES.keys - Desugar::RULES.map(&:to_s)
  end

  EXAMPLES.each do |rule, (src, _)|
    define_method(:"test_#{test_name(rule)}_fires") do
      _, fired = desugar(src)
      assert_includes fired.map(&:to_s), rule
    end
  end

